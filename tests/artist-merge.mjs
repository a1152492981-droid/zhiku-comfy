import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const s=fs.readFileSync(new URL('../runtime.js',import.meta.url),'utf8');
const i=s.indexOf('const __mod_model ='),j=s.indexOf('// ───── store.js',i);
const M=vm.runInNewContext(s.slice(i,j)+'\n__mod_model',{structuredClone});
const d=M.emptyData();
const A=(id,tag,images=[])=>d.artists[id]={id,tag,note:'',images,createdAt:1,collections:[]};
A('p1','artist:artist_pigeon666',[{id:'i1'}]); A('p2','artist:pigeon666');
A('m1','artist:mochizuki_kei',[{id:'i2'}]); A('m2','artist:mochizuki kei',[{id:'i3'}]);
A('z1','artist:Zhibujiloom',[{id:'i4'}]); A('z2','artist:zhibuji loom');
A('f1','artist:chibi',[{id:'i5'}]); A('f2','artist:fine fabric emphasis',[{id:'i6'}]);
d.groups.g={id:'g',name:'x',members:[{artistId:'p1',weight:1},{artistId:'m1',weight:1.2},{artistId:'m2',weight:1},{artistId:'z1',weight:0.8},{artistId:'f1',weight:5}],images:[],collections:[],extra:''};
d.groups.old={id:'old',migratedArtistId:'q',name:'clean_rendering',extra:'clean_rendering',members:[],images:[{id:'i7'}],collections:[]};
d.recent=[{type:'artist',id:'z1'},{type:'group',id:'old'}];
const n=M.normalizeData(JSON.parse(JSON.stringify(d)));
const tags=Object.values(n.artists).map(a=>a.tag.replace('_',' ')).sort();
assert.deepEqual([...tags],['artist:mochizuki kei','artist:pigeon666','artist:zhibuji loom'],tags.join());
const mk=Object.values(n.artists).find(a=>/mochizuki/.test(a.tag)); assert.equal(mk.images.length,2);
assert.equal(Object.values(n.artists).find(a=>a.tag==='artist:pigeon666').images.length,1);
assert(n.groups.old.images.some(i=>i.id==='i7'),'migration retains example images');
const str=M.ticketString(n,{type:'group',id:'g'});
assert(/artist:pigeon666/.test(str)&&/1.2::artist:mochizuki[ _]kei::/.test(str)&&/0.8::artist:zhibuji loom::/.test(str)&&/5::chibi::/.test(str)&&!/artist:artist_|artist:chibi/.test(str),str);
assert.equal(n.recent[0].id, Object.values(n.artists).find(a=>a.tag==='artist:zhibuji loom').id);
console.log('PASS: duplicate artist names merged, fake singles removed:', str);
